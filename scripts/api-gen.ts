// api-gen.ts
// `bun run api:gen`: regenerate src/api/schema.gen.ts from the backend's openapi.json with
// openapi-typescript. `bun run api:check` regenerates in memory and fails when the committed file
// differs (CI drift check, plan section 7).
//
// Source, first match wins:
//   API_SPEC=<url or path>   a pinned release artifact, a local backend, or a file
//   default                  https://api-staging.gezcez.com/openapi.json

import { readFile, writeFile } from "node:fs/promises"
import { resolve } from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const OUT = fileURLToPath(new URL("../src/api/schema.gen.ts", import.meta.url))
const DEFAULT_SPEC = "https://api-staging.gezcez.com/openapi.json"
const HEADER = `// GENERATED by \`bun run api:gen\` (openapi-typescript). Do not edit by hand.
// Endpoints the backend has not published yet are typed in schema.manual.ts.
`

async function loadSpec(source: string): Promise<string> {
	if (/^https?:\/\//.test(source)) {
		const res = await fetch(source, { headers: { accept: "application/json" } })
		if (!res.ok) throw new Error(`GET ${source} -> ${res.status}`)
		return await res.text()
	}
	return await readFile(resolve(source), "utf8")
}

async function main() {
	const check = process.argv.includes("--check")
	const source = process.env.API_SPEC ?? DEFAULT_SPEC
	const spec = JSON.parse(await loadSpec(source))
	const ast = await openapiTS(spec, { alphabetize: true, exportType: true })
	const next = HEADER + `// Source: ${spec.info?.title ?? "gezcez API"} ${spec.info?.version ?? ""}\n\n` + astToString(ast)

	if (check) {
		const current = await readFile(OUT, "utf8").catch(() => "")
		if (current !== next) {
			console.error(`schema.gen.ts is out of date with ${source}. Run \`bun run api:gen\` and commit.`)
			process.exit(1)
		}
		console.log("schema.gen.ts is up to date.")
		return
	}
	await writeFile(OUT, next)
	console.log(`Wrote ${OUT} from ${source}`)
}

main().catch((e) => {
	console.error(e instanceof Error ? e.message : e)
	process.exit(1)
})
